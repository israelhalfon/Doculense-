function hashString(str: string): number {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return Math.abs(h);
}

function buildSynthPattern(
  seedStr: string,
  bpm: number
): {
  melody: NoteEvent[];
  bass: NoteEvent[];
} {
  const seed = hashString(seedStr);
  const step = 60 / bpm / 2;
  const melody: NoteEvent[] = [];
  let t = 0;
  let idx = seed % SCALE_FREQS.length;

  let stepCounter = 0;
  while (t < 4.85) {
    const shift = ((seed >> (stepCounter % 16)) & 3) - 1;
    idx = (idx + shift + SCALE_FREQS.length) % SCALE_FREQS.length;
    const durMultiplier =
      ((seed >> ((stepCounter + 3) % 12)) & 1) === 1 ? 1.8 : 0.9;
    const dur = Math.min(step * durMultiplier, 4.95 - t);
    melody.push({
      freq: SCALE_FREQS[idx],
      start: Number(t.toFixed(2)),
      duration: Number(Math.max(0.18, dur - 0.03).toFixed(2)),
    });
    t += step * (durMultiplier > 1 ? 2 : 1);
    stepCounter++;
  }

  const bass: NoteEvent[] = [
    { freq: BASS_FREQS[seed % BASS_FREQS.length], start: 0.0, duration: 1.2 },
    {
      freq: BASS_FREQS[(seed + 2) % BASS_FREQS.length],
      start: 1.25,
      duration: 1.2,
    },
    {
      freq: BASS_FREQS[(seed + 4) % BASS_FREQS.length],
      start: 2.5,
      duration: 1.2,
    },
    {
      freq: BASS_FREQS[(seed + 1) % BASS_FREQS.length],
      start: 3.75,
      duration: 1.2,
    },
  ];

  return { melody, bass };
}

