function buildTracksForCategory(
  category: SongCategory,
  tuples: CompactSongTuple[]
): SongTrack[] {
  return tuples.map(([title, artist, year, hint], index) => {
    const seedKey = `${category}-${index}-${title}-${artist}`;
    const h = hashString(seedKey);
    const bpm = 96 + (h % 46);
    const instrument = INSTRUMENTS[h % INSTRUMENTS.length];
    const { melody, bass } = buildSynthPattern(seedKey, bpm);

    return {
      id: `${category}-${index + 1}`,
      title,
      artist,
      year,
      category,
      categoryLabel: CATEGORY_LABELS[category],
      hint,
      itunesQuery: `${title.replace(/\(.*?\)/g, "").trim()} ${artist}`,
      bpm,
      instrument,
      melody,
      bass,
    };
  });
}

