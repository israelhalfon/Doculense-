/**
 * Determines whether a song is in Hebrew (no English/Latin characters in title or artist).
 */
export function isHebrewSong(song: SongTrack): boolean {
  const cleanTitle = song.title.replace(/\(.*?\)/g, "").trim();
  const hasHebrew = /[\u0590-\u05FF]/.test(cleanTitle);
  const hasLatin = /[A-Za-z]/.test(cleanTitle) || /[A-Za-z]/.test(song.artist);
  return hasHebrew && !hasLatin;
}

/**
 * Generates 4 distinct choices: 1 correct song + 3 varied distractors.
 * Strictly enforces:
 * 1. Options come ONLY from the same category (or active category pool).
 * 2. If the correct song is in Hebrew, ALL 4 options are strictly in Hebrew (zero English options).
 * 3. If the correct song is in English/foreign language, ALL 4 options are strictly in English/foreign language.
 */
export function generateFourChoices(
  correctSong: SongTrack,
  pool: SongTrack[],
  recentDistractorIds: string[] = []
): SongTrack[] {
  const targetIsHebrew = isHebrewSong(correctSong);

  // 1. Filter strictly to songs of the exact same language (Hebrew vs English)
  const languageMatched = pool.filter(
    (s) => s.id !== correctSong.id && isHebrewSong(s) === targetIsHebrew
  );

  // 2. Filter strictly to songs in the exact same category
  const sameCategoryPool = languageMatched.filter(
    (s) => s.category === correctSong.category
  );

  // Use sameCategoryPool whenever it has at least 3 songs; otherwise fallback to languageMatched from SONGS_DATABASE
  const baseCandidates =
    sameCategoryPool.length >= 3
      ? sameCategoryPool
      : SONGS_DATABASE.filter(
          (s) =>
            s.id !== correctSong.id &&
            s.category === correctSong.category &&
            isHebrewSong(s) === targetIsHebrew
        );

  const effectivePool =
    baseCandidates.length >= 3 ? baseCandidates : languageMatched;

  // Prefer songs not used recently as distractors
  const freshCandidates = effectivePool.filter(
    (s) => !recentDistractorIds.includes(s.id)
  );
  const candidatePool =
    freshCandidates.length >= 3 ? freshCandidates : effectivePool;

  const diffArtist = candidatePool.filter(
    (s) => s.artist !== correctSong.artist
  );
  const sameArtist = candidatePool.filter(
    (s) => s.artist === correctSong.artist
  );

  const shuffle = <T,>(arr: T[]): T[] => {
    const copy = [...arr];
    for (let i = copy.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  };

  const includeSameArtist = Math.random() < 0.3 && sameArtist.length > 0;
  const pickedSameArtist = includeSameArtist
    ? shuffle(sameArtist).slice(0, 1)
    : [];
  const pickedDiffArtist = shuffle(diffArtist).slice(
    0,
    3 - pickedSameArtist.length
  );
  const remainingNeeded =
    3 - pickedSameArtist.length - pickedDiffArtist.length;
  const extraSameArtist =
    remainingNeeded > 0
      ? shuffle(sameArtist)
          .filter((s) => !pickedSameArtist.some((p) => p.id === s.id))
          .slice(0, remainingNeeded)
      : [];

  const distractors = [
    ...pickedSameArtist,
    ...pickedDiffArtist,
    ...extraSameArtist,
  ].slice(0, 3);

  return shuffle([correctSong, ...distractors]);
}
